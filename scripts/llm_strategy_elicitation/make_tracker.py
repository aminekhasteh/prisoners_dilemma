"""Write TRACKER.md: every strategy, how it was elicited (prompt IDs, cost, time) and its tournament status.

Elicitation numbers come from results/raw/*.jsonl. Tournament status is typed into tournament_status.csv (it lives on
another machine); update that file and re-run:  python make_tracker.py
"""
import csv
import datetime as dt
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ET = dt.timezone(dt.timedelta(hours=-5), "EST")
PAL = ["Claude Sonnet 4", "Gemini 2.5 Pro", "GPT-4o", "GPT-5", "Llama 3.3 70B"]
NEW = [("claude-opus-5-5", "Claude Opus 5.5"), ("claude-sonnet-5-5", "Claude Sonnet 5.5"),
       ("claude-haiku-5-5", "Claude Haiku 5.5"), ("gpt-6.1-sol", "GPT-6.1 Sol"), ("gpt-6.1-terra", "GPT-6.1 Terra"),
       ("gpt-6-luna", "GPT-6 Luna")]
RERUN = {"llama-3.3-70b-rerun": ("Llama 3.3 70B (2026 rerun)", ["llama-3.3-70b", "llama-3.3-70b_si"]),
         "gemini-2.5-pro-rerun": ("Gemini 2.5 Pro (2026 rerun)", ["gemini-2.5-pro_si"])}
# The first five Llama runs logged OpenRouter's list price; OpenRouter actually billed about 5.4x that (CoreWeave and
# Bedrock hosts). Later runs log the billed charge. Scale those five so the tracker shows what was paid.
LIST_PRICE_RUNS = {"llama-3.3-70b", "llama-3.3-70b_si", "llama-3.3-70b_t1", "llama-3.3-70b_si_space",
                   "llama-3.3-70b_si_t07"}
BILLED_FACTOR = 5.4  # (OpenRouter usage counter - logged billed runs) / logged list-price cost
USED = {f"{m}_{w}": f"strategy {lab}" for m, lab in NEW for w in ("clean", "si")}
USED.update({t: f"strategy {lab}" for lab, tags in RERUN.values() for t in tags})


def wording(tag, settings):
    v = settings.get("prompt_variant", "clean")
    return "SP" if tag.endswith("_si_space") else ("SI" if v == "si" else "CL")


def runs():
    out = {}
    for f in sorted((HERE / "results" / "raw").glob("*.jsonl")):
        rs = [json.loads(l) for l in open(f)]
        t = [dt.datetime.fromisoformat(r["time"]) for r in rs]
        s = rs[0]["settings"]
        w = wording(f.stem, s)
        cost = defaultdict(float)
        k = BILLED_FACTOR if f.stem in LIST_PRICE_RUNS else 1.0
        for r in rs:
            cost[r["experiment"]] += r["cost_usd"] * k
        trials = defaultdict(set)
        for r in rs:
            if r["choice"] is not None:
                trials[r["key"]].add(r["trial"])
        exps = sorted(cost, key=["memory1", "memory2", "memory3", "framing", "stopping", "gains"].index)
        ids = {"memory1": f"{w}-M1-*", "memory2": f"{w}-M2-*", "memory3": f"{w}-M3-*", "framing": f"{w}-F1..F9-*",
               "stopping": f"{w}-W*-*", "gains": f"{w}-X0..X10-*"}
        o = sorted(r["output_tokens"] for r in rs)
        think = sum(x > 5 for x in o) / len(o)
        out[f.stem] = dict(think=think, out_med=o[len(o) // 2],tag=f.stem, model=s["model"], provider=s["provider"], settings=s, wording=w,
                           prompt_ids=", ".join(ids[e] for e in exps), exps=exps, calls=len(rs),
                           invalid=sum(r["choice"] is None for r in rs), cost=sum(cost.values()), cost_by=dict(cost),
                           start=min(t).astimezone(ET), secs=(max(t) - min(t)).total_seconds(),
                           min_trials=min(len(v) for v in trials.values()), approx=k != 1.0)
    return out


def fmt_secs(s):
    return f"{s / 60:.0f} min" if s >= 90 else f"{s:.0f} s"


def settings_str(s):
    if s["provider"] == "openrouter":
        parts = [f"T={s['temperature']}" if s.get("temperature") is not None else "default T"]
        if s.get("top_p") is not None:
            parts.append(f"top_p={s['top_p']:g}")
        if s.get("seed") is not None:
            parts.append(f"seed={s['seed']}")
        parts.append(f"host={s['host']}" if s.get("host") else "host=any")
        return ", ".join(parts)
    if s["provider"] == "anthropic":
        eff = s.get("effort") or {"claude-opus-5-5": "medium", "claude-haiku-5-5": "medium"}.get(s["model"], "high")
        return f"effort {eff}{'' if s.get('effort') else ' (API default)'}, adaptive thinking, no sampling params"
    return f"reasoning effort {s.get('reasoning_effort') or 'API default'}"


def main():
    R = runs()
    st = list(csv.DictReader(open(HERE / "tournament_status.csv")))
    stat = {(r["group"], r["condition"]): r for r in st}
    conds = ["standard 63", "standard 77-308", "noise1", "noise5"]

    def tcell(group, cond):
        r = stat.get((group, cond))
        if not r:
            return "n/a"
        when = r["end_et"].replace("ETA ", "ETA ") if r["status"] != "Done" else r["end_et"]
        return f"{r['status']} ({when})" if r["status"] != "Done" else "Done"

    L = ["# Strategy tracker\n",
         f"Generated by `make_tracker.py` on {dt.datetime.now(ET):%b %d %Y, %I:%M %p} ET. Prompt IDs are defined in "
         "`PROMPTS.md`. Tournament status is copied from the tournament thread into `tournament_status.csv` "
         "(times in ET).\n",
         "## 1. Strategies\n",
         "One row per tournament player. Memory-1 players are named \"LLM: <model>\", memory-2 players \"LLM-m2: <model>\".\n",
         "| # | Model | Source | Memory | Prompt IDs | Trials per scenario | Elicitation cost | Std 63 | Std 77-308 | Noise 1% | Noise 5% |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    n = 0
    for mem, grp in [("memory-1", "pal_m1"), ("memory-2", "pal_m2")]:
        for m in PAL:
            n += 1
            ids = "paper's own runs (its text = `SI-M1-*`)" if mem == "memory-1" else "paper's own runs (its text = `SI-M2-*`)"
            L.append(f"| {n} | {m} | Pal et al. 2026, Table {'S12' if mem == 'memory-1' else 'S11'} | {mem} | {ids} | 50 | "
                     f"by the paper | " + " | ".join(tcell(grp, c) for c in conds) + " |")
    for mid, lab in NEW + [(k, v[0]) for k, v in RERUN.items()]:
        tags = RERUN[mid][1] if mid in RERUN else [f"{mid}_clean", f"{mid}_si"]
        src = "2026 rerun of a paper model" if mid in RERUN else "new elicitation (2026)"
        for mem, exp in [("memory-1", "memory1"), ("memory-2", "memory2")]:
            if not all(exp in R[t]["exps"] for t in tags):
                continue
            n += 1
            ids = " + ".join(f"`{R[t]['wording']}-{'M1' if exp == 'memory1' else 'M2'}-*`" for t in tags)
            trials = sum(R[t]["min_trials"] for t in tags)
            cost = sum(R[t]["cost_by"].get(exp, 0) for t in tags)
            approx = "≈" if any(R[t]["approx"] for t in tags) else ""
            L.append(f"| {n} | {lab} | {src} | {mem} | {ids} | {trials} | {approx}${cost:.2f} | "
                     + " | ".join(tcell("new", c) for c in conds) + " |")
    M3 = [("claude-opus-5-5", "Claude Opus 5.5"), ("claude-sonnet-5-5", "Claude Sonnet 5.5"),
          ("claude-sonnet-5-5_clean_effort-xhigh", "Claude Sonnet 5.5, effort xhigh"),
          ("claude-haiku-5-5", "Claude Haiku 5.5"), ("gpt-6.1-sol", "GPT-6.1 Sol"), ("gpt-6.1-terra", "GPT-6.1 Terra"),
          ("gpt-6-luna", "GPT-6 Luna"), ("llama-3.3-70b", "Llama 3.3 70B (2026 rerun)")]
    for mid, lab in M3:
        tag = f"{mid}_m3" if "effort" in mid else f"{mid}_clean_m3"
        if tag not in R:
            continue
        r = R[tag]
        n += 1
        done = "" if r["min_trials"] >= 50 and r["calls"] >= 4250 else " (incomplete: stopped by the Anthropic workspace spend limit)"
        L.append(f"| {n} | {lab} | {'2026 rerun of a paper model' if 'llama' in mid else 'new elicitation (2026)'} | "
                 f"memory-3 | `CL-M3-*` | {r['min_trials']}{done} | ${r['cost']:.2f} | "
                 + (" | ".join(["Planned (after the new-field run)"] * 4) if not done else " | ".join(["not scheduled"] * 4))
                 + " |")
    L += ["", "Gemini 2.5 Pro (2026 rerun) has no memory-2 player: its memory-2 scenarios were not run (about $20).", ""]

    L += ["## 2. Tournament runs\n",
          "All runs use 250 repetitions and Knight et al.'s seeds (20 for standard, 13 for noise 1%, 7 for noise 5%); "
          "noisy tournaments exist only at 63 turns. No API cost.\n",
          "| Players | Condition | Field | Machine | Status | Start (ET) | End or ETA (ET) | Duration | Results | Commit |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    names = {"pal_m1": "Pal et al. memory-1 (5)", "pal_m2": "Pal et al. memory-2 (5)",
             "new": "New strategies (8 memory-1 + 7 memory-2)", "new_m3": "Memory-3 strategies (7)"}
    for r in st:
        L.append(f"| {names[r['group']]} | {r['condition']} | {r['field']} | {r['machine']} | {r['status']} | "
                 f"{r['start_et']} | {r['end_et']} | {r['duration']} | `{r['results']}` | {r['commit'] or '—'} |")

    L += ["", "## 3. Elicitation runs (API calls)\n",
          "Every API run so far, including the checks that did not become tournament strategies. 50 trials per "
          "scenario; wall time is first to last reply.\n",
          "Thinking column: share of calls where the model wrote more than 5 output tokens (hidden thinking or "
          "reasoning; the visible answer is 1 to 3 tokens), and the median output tokens. Nothing was ever switched "
          "off: every run used the API's defaults unless an effort is listed, and the adaptive models chose how much "
          "to think.\n",
          "| Run | Model | Settings | Thinking | Prompt IDs | Calls | Invalid | Cost | Started (ET) | Wall time | Used for |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    order = sorted(R.values(), key=lambda r: (r["start"], r["tag"]))
    tot = defaultdict(float)
    for r in order:
        tot[r["provider"]] += r["cost"]
        used = USED.get(r["tag"], "Llama replication check" if "llama" in r["tag"]
                        else ("memory-3 strategy" if r["tag"].endswith("_m3") else
                              ("Sonnet xhigh memory-2" if r["tag"].endswith("xhigh_m2") else
                               ("effort check (memory-1 only)" if "effort" in r["tag"] else "check"))))
        th = "n/a" if r["provider"] == "openrouter" and "gemini" not in r["model"] else f"{r['think']:.0%} (median {r['out_med']})"
        L.append(f"| `{r['tag']}` | {r['model']} | {settings_str(r['settings'])} | {th} | `{r['prompt_ids']}` | {r['calls']:,} | "
                 f"{r['invalid']} | {'≈' if r['approx'] else ''}${r['cost']:.2f} | {r['start']:%b %d %I:%M %p} | "
                 f"{fmt_secs(r['secs'])}{' (two sittings, rate limited)' if r['tag'] == 'gemini-2.5-pro_si' else ''} | {used} |")
    L += ["", "Total API spend by provider: " + ", ".join(f"{k} ${v:.2f}" for k, v in sorted(tot.items()))
          + f"; all ${sum(tot.values()):.2f}. ≈ marks the five early Llama runs, which logged OpenRouter's list "
          "price; their cost here is scaled to what OpenRouter billed. OpenRouter's own usage counter (including "
          "smoke tests and probes) read $7.29 after the Gemini run.", ""]
    (HERE / "TRACKER.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
