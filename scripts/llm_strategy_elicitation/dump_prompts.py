"""Write PROMPTS.md: every prompt the pipeline sends, with its ID, exactly as sent, plus the request settings."""
import importlib
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load(variant):
    os.environ["PD_PROMPT_VARIANT"] = variant
    os.environ.pop("PD_PROMPT_JOIN", None)
    import prompts
    return importlib.reload(prompts)


def block(text):
    return "```\n" + text + "\n```\n"


def title(s):
    if s.kind == "round1":
        return "round 1"
    if s.kind == "round2":
        return f"round 2, round 1 was {s.prev1}"
    if s.memory == 2:
        return f"later round, two rounds ago {s.prev2}, last round {s.prev1}"
    return f"later round, last round {s.prev1}"


p = load("si")
out = ["# Prompts sent by the pipeline\n",
       "Generated by `dump_prompts.py` from `prompts.py`. Each prompt is one user message in a fresh conversation; "
       "nothing else is sent. Outcomes are written with the model's own move first (CD = the model played L, the "
       "other agent played R; L = cooperate, R = defect).\n",
       "## Prompt IDs\n",
       "`<wording>-<block>-<scenario>`, for example `SI-M1-CD` or `CL-M2-CC-CD`.\n",
       "| Part | Values |\n|---|---|\n"
       "| wording | `CL` our clean wording; `SI` the paper's text verbatim; `SP` the paper's text joined into one paragraph |\n"
       "| block | `M1` memory-1; `M2` memory-2; `F1`..`F9` framings; `W0.01`..`W0.5` stopping probability; `X0`..`X10` payoff cost |\n"
       "| scenario | `R1` first round; `CC`, `CD`, `DC`, `DD` last round; `R2-CD` second round after CD; `CC-CD` two rounds ago CC, last round CD |\n",
       "A set of prompts is written with `*`: `SI-M1-*` is the 5 memory-1 prompts in the paper's wording.\n",
       "## Request\n",
       "- System prompt: `Follow specified goals`\n"
       "- Answer parsing: the reply, stripped of spaces, quotes, backticks, asterisks and a final period, must be "
       "exactly `L` (cooperate) or `R` (defect). Anything else is logged as invalid and re-asked (up to 3 times).\n"
       "- Model settings differ by run and are listed in the tracker (`TRACKER.md`) and saved with every reply.\n",
       "## The wordings\n",
       "- **`SI` (paper verbatim):** SI section 4 as printed, including the literal \"point(s)\" and, in the memory-2 "
       "later-round prompt, the SI line that gives the other agent the model's own payoff for the previous round.\n"
       "- **`CL` (clean):** the same text with \"1 point\" / \"N points\" instead of \"point(s)\", and the other agent's "
       "real payoff in that memory-2 line. Everything else is identical.\n"
       "- **`SP`:** the `SI` text with the lines joined by single spaces instead of line breaks (one Llama test run).\n"
       "- The payoff-table lines are the same in all of them (\"both of you get 1 points\", as in the SI).\n"]

for variant, wid in [("si", "SI"), ("clean", "CL")]:
    p = load(variant)
    for exp, name in [("memory1", "Memory-1 (5 prompts)"), ("memory2", "Memory-2 (21 prompts)")]:
        out.append(f"## {name}, `{wid}` wording\n")
        for s in p.scenarios(exp):
            out += [f"### `{p.prompt_uid(s, wid)}`: {title(s)}\n", block(p.build_prompt(s))]

p = load("si")
out.append("## Treatments (memory-1 scenarios only, `SI` wording)\n")
out.append("Each treatment prompt is the matching `SI-M1-*` prompt with one change. Framings add their sentence "
           "after \"Your final reward is the total number of points you accumulate in all rounds.\"; stopping "
           "probabilities add \"After each round the interaction ends with probability w.\" after \"Your interaction "
           "is over several rounds.\"; payoff costs replace the payoffs (3, 0, 5, 1) with (10, 0, 10 + x, x).\n")
out.append("| IDs | Change |\n|---|---|")
for k, txt in p.FRAMINGS.items():
    out.append(f"| `SI-{p.FRAMING_IDS[k]}-*` | framing: \"{txt}\" |")
for w in p.STOPPING_W:
    out.append(f"| `SI-W{w}-*` | stopping probability {w} |")
for x in p.GAINS_X:
    out.append(f"| `SI-X{x}-*` | payoffs (10, 0, {10 + x}, {x}) |")
out.append("")
out.append("Example, `SI-F2-CD`:\n")
s = [s for s in p.scenarios("framing") if s.treatment == "competitive_exploit" and s.prev1 == "CD"][0]
out.append(block(p.build_prompt(s)))
(HERE / "PROMPTS.md").write_text("\n".join(out))
print("wrote", HERE / "PROMPTS.md")
