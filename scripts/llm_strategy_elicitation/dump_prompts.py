"""Write PROMPTS.md: every prompt the pipeline sends, exactly as sent, plus the request settings."""
import importlib
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent


def render(variant):
    os.environ["PD_PROMPT_VARIANT"] = variant
    import prompts
    importlib.reload(prompts)
    return prompts


def block(text):
    return "```\n" + text + "\n```\n"


def title(s):
    if s.kind == "round1":
        return "Round 1"
    if s.kind == "round2":
        return f"Round 2, round 1 was {s.prev1}"
    if s.memory == 2:
        return f"Later round, two rounds ago {s.prev2}, last round {s.prev1}"
    return f"Later round, last round {s.prev1}"


out = ["# Prompts sent by the pipeline\n",
       "Generated by `dump_prompts.py` from `prompts.py`. Outcomes are written with the model's own move first "
       "(CD = the model played L, the other agent played R). Each prompt is one user message in a fresh "
       "conversation; nothing else is sent.\n",
       "## Request\n",
       "- System prompt: `Follow specified goals`\n"
       "- Llama 3.3 70B (OpenRouter): `temperature=0`, `top_p=1e-8`, `max_tokens=50` (the paper's settings)\n"
       "- Answer parsing: the reply, stripped of spaces, quotes, backticks, asterisks and a final period, must be "
       "exactly `L` (counted as cooperate) or `R` (defect). Anything else is logged as invalid and re-asked.\n",
       "## The two wordings\n",
       "- **`si` (paper verbatim):** the text of SI section 4 as printed, including the literal \"point(s)\" and, "
       "in the memory-2 later-round prompt, the SI line that gives the other agent the model's own payoff for "
       "the previous round (\"you got [a x-1 y-1] point(s) and they got [a x-1 y-1] point(s)\").\n"
       "- **`clean` (our first runs):** the same text with \"1 point\" / \"N points\" instead of \"point(s)\", and "
       "the other agent's real payoff in that memory-2 line. Everything else is identical.\n"
       "- The payoff-table lines are the same in both (\"both of you get 1 points\", as in the SI).\n"]

p = render("si")
out.append("## Memory-1 prompts (5), `si` wording\n")
for s in p.scenarios("memory1"):
    out += [f"### {title(s)}\n", block(p.build_prompt(s))]
out.append("## Memory-2 prompts (21), `si` wording\n")
out.append("Round 1 is the same text as memory-1 round 1.\n")
for s in p.scenarios("memory2")[1:]:
    out += [f"### {title(s)}\n", block(p.build_prompt(s))]
c = render("clean")
out.append("## The same prompts in the `clean` wording (examples)\n")
for s in [c.scenarios("memory1")[3], c.scenarios("memory2")[-6]]:
    out += [f"### {title(s)}\n", block(c.build_prompt(s))]
p = render("si")
out.append("## Treatments (memory-1 scenarios only), one example each, `si` wording\n")
for exp, i in [("framing", 3), ("stopping", 3), ("gains", 5 * 3 + 3)]:
    s = p.scenarios(exp)[i]
    out += [f"### {exp}: {s.treatment}, {title(s)}\n", block(p.build_prompt(s))]
(HERE / "PROMPTS.md").write_text("\n".join(out))
print("wrote", HERE / "PROMPTS.md")
